-- sportbooking - DDL de referencia (schema "platform")
-- =============================================================================
-- Insumo para una futura adopcion de Flyway/Liquibase (deuda #3 de la
-- bitacora). NO lo consume el build, ni spring.sql.init, ni @Sql: vive fuera
-- del classpath y es solo documentacion ejecutable del esquema.
--
-- Como se genero: derivado 1:1 de las anotaciones de las entities JPA
-- (GenerationType.IDENTITY, @ManyToOne/@JoinColumn, @Column(unique,
-- nullable), @UniqueConstraint de user_venue_role). Es un baseline
-- NORMALIZADO, equivalente funcional al esquema que Hibernate levanta con
-- ddl-auto=create-drop en el perfil "test". La base de dev real crecio por
-- etapas y arrastra ruido (mezcla de bigserial + secuencias explicitas
-- redundantes y secuencias huerfanas de IDENTITY); ese dump no se copio aca
-- porque al momento de escribir esto no habia Postgres accesible. Cuando se
-- adopte Flyway de verdad, tomar este archivo como V1__baseline.sql y
-- validarlo contra un pg_dump real de dev.
--
-- Convencion: los nombres de tabla/columna son snake_case, igual que en las
-- entities (campo Java -> columna). Las FK llevan el prefijo "fk_".
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS platform;

-- -----------------------------------------------------------------------------
-- user / role / user_global_role (roles globales del usuario)
-- -----------------------------------------------------------------------------
CREATE TABLE platform.role (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE platform."user" (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name          VARCHAR(255),
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP,
    CONSTRAINT uk_user_username UNIQUE (username),
    CONSTRAINT uk_user_email UNIQUE (email)
);

CREATE TABLE platform.user_global_role (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_user_id BIGINT,
    fk_role_id BIGINT
);

-- -----------------------------------------------------------------------------
-- venue / court / time_block / court_schedule
-- -----------------------------------------------------------------------------
CREATE TABLE platform.venue (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    address    VARCHAR(255),
    phone      VARCHAR(255),
    created_at TIMESTAMP
);

CREATE TABLE platform.court (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_venue_id   BIGINT,
    name          VARCHAR(255),
    sport_type    VARCHAR(255),
    indoor        BOOLEAN,
    surface_type  VARCHAR(255),
    max_players   INTEGER,
    created_at    TIMESTAMP,
    is_active     BOOLEAN
);

CREATE TABLE platform.time_block (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_venue_id BIGINT,
    block_group VARCHAR(255),
    label       VARCHAR(255),
    start_time  TIME,
    end_time    TIME
);

CREATE TABLE platform.court_schedule (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_court_id       BIGINT,
    fk_time_block_id  BIGINT,
    day_of_week       SMALLINT,
    is_enabled        BOOLEAN,
    notes             VARCHAR(255)
);

-- -----------------------------------------------------------------------------
-- user_venue_role (membresia: usuario + venue + rol)
-- -----------------------------------------------------------------------------
CREATE TABLE platform.user_venue_role (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_venue_id  BIGINT,
    fk_user_id   BIGINT,
    fk_role_id   BIGINT,
    CONSTRAINT user_venue_role_unique UNIQUE (fk_venue_id, fk_user_id, fk_role_id)
);

-- -----------------------------------------------------------------------------
-- reservation
-- -----------------------------------------------------------------------------
CREATE TABLE platform.reservation (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date                    DATE,
    fk_court_id             BIGINT,
    fk_time_block_id        BIGINT,
    fk_reserved_by_user_id  BIGINT,
    fk_reserved_for_user_id BIGINT,
    reserved_for_name       VARCHAR(255),
    status                  VARCHAR(255),
    payment_status          VARCHAR(255),
    created_at              TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- FKs (Hibernate las administra con ddl-auto=update; se dejan explicitas para
-- que el baseline sea autocontenido de cara a Flyway).
-- -----------------------------------------------------------------------------
ALTER TABLE platform.user_global_role
    ADD CONSTRAINT fk_user_global_role_user FOREIGN KEY (fk_user_id) REFERENCES platform."user" (id),
    ADD CONSTRAINT fk_user_global_role_role FOREIGN KEY (fk_role_id) REFERENCES platform.role (id);

ALTER TABLE platform.court
    ADD CONSTRAINT fk_court_venue FOREIGN KEY (fk_venue_id) REFERENCES platform.venue (id);

ALTER TABLE platform.time_block
    ADD CONSTRAINT fk_time_block_venue FOREIGN KEY (fk_venue_id) REFERENCES platform.venue (id);

ALTER TABLE platform.court_schedule
    ADD CONSTRAINT fk_court_schedule_court FOREIGN KEY (fk_court_id) REFERENCES platform.court (id),
    ADD CONSTRAINT fk_court_schedule_time_block FOREIGN KEY (fk_time_block_id) REFERENCES platform.time_block (id);

ALTER TABLE platform.user_venue_role
    ADD CONSTRAINT fk_user_venue_role_venue FOREIGN KEY (fk_venue_id) REFERENCES platform.venue (id),
    ADD CONSTRAINT fk_user_venue_role_user FOREIGN KEY (fk_user_id) REFERENCES platform."user" (id),
    ADD CONSTRAINT fk_user_venue_role_role FOREIGN KEY (fk_role_id) REFERENCES platform.role (id);

ALTER TABLE platform.reservation
    ADD CONSTRAINT fk_reservation_court FOREIGN KEY (fk_court_id) REFERENCES platform.court (id),
    ADD CONSTRAINT fk_reservation_time_block FOREIGN KEY (fk_time_block_id) REFERENCES platform.time_block (id),
    ADD CONSTRAINT fk_reservation_reserved_by FOREIGN KEY (fk_reserved_by_user_id) REFERENCES platform."user" (id),
    ADD CONSTRAINT fk_reservation_reserved_for FOREIGN KEY (fk_reserved_for_user_id) REFERENCES platform."user" (id);
