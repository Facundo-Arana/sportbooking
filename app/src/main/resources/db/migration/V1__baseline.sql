-- =============================================================================
-- sportbooking - V1 baseline (schema "platform")
-- =============================================================================
-- Baseline unico y autocontenido del esquema (deuda #2 y #3 de la bitacora).
-- Reemplaza a db/schema-reference.sql como fuente del DDL: Flyway es el dueno
-- unico y la app solo valida (ddl-auto=validate).
--
-- Derivado de db/schema-reference.sql (que a su vez nace 1:1 de las entities
-- JPA) y endurecido segun el change "endurecer-esquema-con-flyway":
--   - IDENTITY como unico mecanismo de generacion de ids (sin bigserial ni
--     secuencias explicitas huerfanas).
--   - tabla "user" renombrada a app_user (palabra reservada).
--   - updated_at eliminado (nunca se seteaba).
--   - NOT NULL en FKs y columnas de negocio obligatorias.
--   - CHECK de dominios controlados (status/payment_status/day_of_week/rango).
--   - indice unico parcial anti-doble-reserva.
--   - FKs con nombres descriptivos fk_*.
--
-- Inmutable una vez aplicada: para cambiar el esquema, agregar V2, V3, ...
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS platform;

-- -----------------------------------------------------------------------------
-- user / role / user_global_role (roles globales del usuario)
-- -----------------------------------------------------------------------------
CREATE TABLE platform.role (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE platform.app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name          VARCHAR(255),
    created_at    TIMESTAMP    NOT NULL,
    CONSTRAINT uk_user_username UNIQUE (username),
    CONSTRAINT uk_user_email UNIQUE (email)
);

CREATE TABLE platform.user_global_role (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_user_id BIGINT NOT NULL,
    fk_role_id BIGINT NOT NULL
);

-- -----------------------------------------------------------------------------
-- venue / court / time_block / court_schedule
-- -----------------------------------------------------------------------------
CREATE TABLE platform.venue (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    address    VARCHAR(255),
    phone      VARCHAR(255),
    created_at TIMESTAMP    NOT NULL
);

CREATE TABLE platform.court (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_venue_id  BIGINT       NOT NULL,
    name         VARCHAR(255) NOT NULL,
    sport_type   VARCHAR(255),
    indoor       BOOLEAN      NOT NULL,
    surface_type VARCHAR(255),
    max_players  INTEGER,
    created_at   TIMESTAMP    NOT NULL,
    is_active    BOOLEAN      NOT NULL
);

CREATE TABLE platform.time_block (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_venue_id BIGINT       NOT NULL,
    block_group VARCHAR(255) NOT NULL,
    label       VARCHAR(255) NOT NULL,
    start_time  TIME         NOT NULL,
    end_time    TIME         NOT NULL,
    CONSTRAINT ck_time_block_range CHECK (start_time < end_time)
);

CREATE TABLE platform.court_schedule (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_court_id      BIGINT   NOT NULL,
    fk_time_block_id BIGINT   NOT NULL,
    day_of_week      SMALLINT NOT NULL,
    is_enabled       BOOLEAN  NOT NULL,
    notes            VARCHAR(255),
    CONSTRAINT ck_court_schedule_day_of_week CHECK (day_of_week BETWEEN 0 AND 6)
);

-- -----------------------------------------------------------------------------
-- user_venue_role (membresia: usuario + venue + rol)
-- -----------------------------------------------------------------------------
CREATE TABLE platform.user_venue_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_venue_id BIGINT NOT NULL,
    fk_user_id  BIGINT NOT NULL,
    fk_role_id  BIGINT NOT NULL,
    CONSTRAINT user_venue_role_unique UNIQUE (fk_venue_id, fk_user_id, fk_role_id)
);

-- -----------------------------------------------------------------------------
-- reservation
-- -----------------------------------------------------------------------------
CREATE TABLE platform.reservation (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date                    DATE         NOT NULL,
    fk_court_id             BIGINT       NOT NULL,
    fk_time_block_id        BIGINT       NOT NULL,
    fk_reserved_by_user_id  BIGINT       NOT NULL,
    fk_reserved_for_user_id BIGINT,
    reserved_for_name       VARCHAR(255),
    status                  VARCHAR(255) NOT NULL,
    payment_status          VARCHAR(255) NOT NULL,
    created_at              TIMESTAMP    NOT NULL,
    CONSTRAINT ck_reservation_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_reservation_payment_status CHECK (payment_status IN ('PENDING', 'PAID', 'REFUNDED'))
);

-- -----------------------------------------------------------------------------
-- FKs con nombres descriptivos fk_*
-- -----------------------------------------------------------------------------
ALTER TABLE platform.user_global_role
    ADD CONSTRAINT fk_user_global_role_user FOREIGN KEY (fk_user_id) REFERENCES platform.app_user (id),
    ADD CONSTRAINT fk_user_global_role_role FOREIGN KEY (fk_role_id) REFERENCES platform.role (id);

ALTER TABLE platform.court
    ADD CONSTRAINT fk_court_venue FOREIGN KEY (fk_venue_id) REFERENCES platform.venue (id);

ALTER TABLE platform.time_block
    ADD CONSTRAINT fk_time_block_venue FOREIGN KEY (fk_venue_id) REFERENCES platform.venue (id);

ALTER TABLE platform.court_schedule
    ADD CONSTRAINT fk_court_schedule_court FOREIGN KEY (fk_court_id) REFERENCES platform.court (id),
    ADD CONSTRAINT fk_court_schedule_time_block FOREIGN KEY (fk_time_block_id) REFERENCES platform.time_block (id);

ALTER TABLE platform.user_venue_role
    ADD CONSTRAINT fk_user_venue_role_venue FOREIGN KEY (fk_venue_id) REFERENCES platform.venue (id),
    ADD CONSTRAINT fk_user_venue_role_user FOREIGN KEY (fk_user_id) REFERENCES platform.app_user (id),
    ADD CONSTRAINT fk_user_venue_role_role FOREIGN KEY (fk_role_id) REFERENCES platform.role (id);

ALTER TABLE platform.reservation
    ADD CONSTRAINT fk_reservation_court FOREIGN KEY (fk_court_id) REFERENCES platform.court (id),
    ADD CONSTRAINT fk_reservation_time_block FOREIGN KEY (fk_time_block_id) REFERENCES platform.time_block (id),
    ADD CONSTRAINT fk_reservation_reserved_by FOREIGN KEY (fk_reserved_by_user_id) REFERENCES platform.app_user (id),
    ADD CONSTRAINT fk_reservation_reserved_for FOREIGN KEY (fk_reserved_for_user_id) REFERENCES platform.app_user (id);

-- -----------------------------------------------------------------------------
-- Anti doble reserva (D4 del design): no puede haber dos reservas ACTIVAS con
-- la misma (cancha, fecha, franja). Un indice unico PARCIAL lo expresa exacto y
-- corre en la base: cierra la race del check-then-act de ReservationService.
-- Una reserva CANCELLED queda fuera del indice, asi que libera la franja.
-- -----------------------------------------------------------------------------
CREATE UNIQUE INDEX reservation_active_slot_unique
    ON platform.reservation (fk_court_id, date, fk_time_block_id)
    WHERE status <> 'CANCELLED';
